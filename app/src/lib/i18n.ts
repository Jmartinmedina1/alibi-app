export type Key = keyof typeof S;
export function t(lang: Lang, key: Key, vars?: Record<string, string>): string {
  let s = (S[key] as any)[lang] ?? (S[key] as any).en;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}

